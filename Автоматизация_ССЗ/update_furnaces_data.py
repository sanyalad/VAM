# Clear devices for a specific furnace and get its location ID
def clear_furnace(name):
    loc = inventory_db.get_location_by_name(ws_id, name)
    if loc:
        conn = inventory_db._get_conn()
        cursor = conn.cursor()
        cursor.execute("DELETE FROM devices WHERE location_id = ?", (loc["id"],))
        conn.commit()
        conn.close()
        return loc["id"]
    else:
        return inventory_db.add_location(ws_id, name, "furnace")

